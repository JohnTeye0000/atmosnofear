"""SYNTHETIC trips for software testing only.

Generated by code with a made-up rush-hour pattern. It is never evidence about
Kumasi: every row is labelled `synthetic` and the evaluator copies that label
into its output. Rain is deliberately NOT simulated.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

SEGMENT_ID = "SYN_SEGMENT"
LENGTH_M = 5000.0


def synthetic_segments() -> pd.DataFrame:
    return pd.DataFrame([{"segment_id": SEGMENT_ID, "name": "synthetic test segment", "direction": "n/a",
                          "start_lat": 0.0, "start_lon": 0.0, "end_lat": 0.0, "end_lon": 0.0,
                          "length_m": LENGTH_M, "notes": "SYNTHETIC - not a real road"}])


def generate_trips(days: int = 28, trips_per_day: int = 40, seed: int = 0,
                   start: str = "2025-01-06") -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    day0 = pd.Timestamp(start, tz="UTC")
    rows = []
    for d in range(days):
        hours = rng.uniform(6, 20, trips_per_day)
        for i, hr in enumerate(np.sort(hours)):
            peak = np.exp(-((hr - 8) ** 2) / 2) + np.exp(-((hr - 17) ** 2) / 2)  # two rush hours
            duration = 600 * (1 + 0.8 * peak) * rng.lognormal(0, 0.15)
            rows.append({"trip_id": f"syn{d:03d}_{i:03d}", "segment_id": SEGMENT_ID,
                         "start_time_utc": (day0 + pd.Timedelta(days=d, hours=float(hr))).isoformat(),
                         "duration_s": round(float(duration), 1), "vehicle_type": "trotro",
                         "collector_id": "P001", "data_label": "synthetic"})
    return pd.DataFrame(rows)
